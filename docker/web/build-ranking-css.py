"""Build the ranking page's stylesheet from the shipped Semantic UI bundle.

Keep complete components, including hover/focus, guest buttons and review badges.
Run this after changing oj-bundle.css; no additional Python packages are needed.
"""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2] / 'web/template/syzoj/css'
source = (root / 'oj-bundle.css').read_text()
markers = list(re.finditer(r'/\* ===================== ([^\n]*?) ===================== \*/', source))
sections = {
    match.group(1).split('(')[0]: source[match.end():markers[i+1].start() if i+1 < len(markers) else len(source)]
    for i, match in enumerate(markers)
}
semantic = sections['semantic.min.css']
banners = list(re.finditer(r'/\*!\s*\n\s*\* # Semantic UI [^\n]+ - ([^\n]+)', semantic))
required = {'Reset', 'Site', 'Button', 'Container', 'Header', 'Icon', 'Label', 'Grid', 'Dropdown', 'Transition'}
components = [
    semantic[match.start():banners[i+1].start() if i+1 < len(banners) else len(semantic)]
    for i, match in enumerate(banners) if match.group(1).strip() in required
]
assert {match.group(1).strip() for match in banners} >= required
styles = '/*! Generated by docker/web/build-ranking-css.py from oj-bundle.css; retain upstream MIT notices. */\n'
# Semantic's menu stylesheet is bundled after Grid without its own versioned
# banner. Keep that whole block, and the incumbent Bootstrap container spacing.
container = re.search(r'\.container\{[^}]*\}', sections['bootstrap.min.css']).group()
bootstrap_notice = re.search(r'/\*![\s\S]*?\*/', sections['bootstrap.min.css']).group()
styles += bootstrap_notice + '\n' + semantic[:banners[0].start()]
styles += container + '\n.container:before,.container:after{display:table;content:" "}.container:after{clear:both}\n'
styles += sections['latin.css'] + sections['style.css'] + ''.join(components)
styles += sections['oj-bg.css'] + sections['oj-theme.css']
assert '.ui.menu' in styles and '.ui.simple.dropdown' in styles
(root / 'oj-ranking.css').write_text(styles.rstrip() + '\n')
